#!/usr/bin/env python3
"""Generate the original Lindo Selected Copy geometry in SVG, SwiftUI and AppKit.

The raster concept sheets are exploration references. These are native paths,
constructed explicitly and kept identical across production formats.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parent.parent
INK, PAPER, LIME = '#1D2E29', '#F4F2E9', '#B7E35A'
BACK = [('M',436,192),('L',684,192),('Q',700,192,712,204),('L',820,312),
        ('Q',832,324,832,342),('L',832,662),('Q',832,732,768,732),
        ('L',768,442),('Q',768,414,748,394),('L',634,280),
        ('Q',614,260,586,260),('L',360,260),('Q',360,192,436,192),('Z',)]
FRONT = [('M',276,308),('L',548,308),('Q',570,308,570,330),('L',570,398),
         ('Q',570,450,622,450),('L',694,450),('Q',716,450,716,472),
         ('L',716,746),('Q',716,832,630,832),('L',276,832),
         ('Q',192,832,192,748),('L',192,392),('Q',192,308,276,308),('Z',)]
# Custom-drawn wordmark, not a substituted or embedded font.
WORD = ('M0 0H20V78H65V98H0Z M89 0H109V98H89Z '
        'M138 98V0H158L209 64V0H229V98H210L158 33V98Z '
        'M259 0H294C329 0 350 19 350 49S329 98 294 98H259Z '
        'M279 19V79H294C316 79 329 69 329 49S316 19 294 19Z '
        'M421 -2C450 -2 472 19 472 49S450 100 421 100S370 79 370 49S392 -2 421 -2Z '
        'M421 18C403 18 391 31 391 49S403 80 421 80S451 67 451 49S439 18 421 18Z')

def path(ops): return ' '.join(str(v) for op in ops for v in op)
def svg(body, view='160 160 704 704', width=704, height=704):
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view}" width="{width}" height="{height}">{body}</svg>\n'
def mark(front=INK, back=LIME):
    return f'<path fill="{back}" d="{path(BACK)}"/><path fill="{front}" d="{path(FRONT)}"/>'
def swift(ops):
    lines=[]
    for op,*v in ops:
        if op=='M': line=f'p.move(to: CGPoint(x: {v[0]}, y: {v[1]}))'
        elif op=='L': line=f'p.addLine(to: CGPoint(x: {v[0]}, y: {v[1]}))'
        elif op=='Q': line=f'p.addQuadCurve(to: CGPoint(x: {v[2]}, y: {v[3]}), control: CGPoint(x: {v[0]}, y: {v[1]}))'
        else: line='p.closeSubpath()'
        lines.append('        '+line)
    return '\n'.join(lines)
def write(name,text):
    dest=ROOT/name; dest.parent.mkdir(parents=True,exist_ok=True); dest.write_text(text)

write('Icon/Mark.svg',svg(mark()))
write('Icon/AppIcon.icon/Assets/back.svg',svg(f'<path fill="{LIME}" d="{path(BACK)}"/>','0 0 1024 1024',1024,1024))
write('Icon/AppIcon.icon/Assets/front.svg',svg(f'<path fill="{PAPER}" d="{path(FRONT)}"/>','0 0 1024 1024',1024,1024))
write('Icon/AppIcon.icon/icon.json',json.dumps({'fill':{'solid':'srgb:0.11373,0.18039,0.16078,1.00000'},'groups':[{'layers':[{'glass':False,'image-name':'back.svg','name':'Extra copy'},{'glass':False,'image-name':'front.svg','name':'Selected copy'}],'shadow':{'kind':'neutral','opacity':0.15},'translucency':{'enabled':False,'value':0}}],'supported-platforms':{'squares':['macOS']}},indent=2)+'\n')
assets='launch/brand/assets/'
write(assets+'mark.svg',svg(mark()))
write(assets+'mark-mono.svg',svg(mark(INK,INK)))
write(assets+'mark-reverse.svg',svg(mark(PAPER,PAPER)))
write(assets+'wordmark.svg',svg(f'<path fill="{INK}" fill-rule="evenodd" d="{WORD}"/>','0 -2 472 102',472,102))
write(assets+'wordmark-reverse.svg',svg(f'<path fill="{PAPER}" fill-rule="evenodd" d="{WORD}"/>','0 -2 472 102',472,102))
for reverse in [False,True]:
    color=PAPER if reverse else INK
    content=f'<g transform="translate(-22 -22) scale(.22)">{mark(color,LIME)}</g><path transform="translate(195 35)" fill="{color}" fill-rule="evenodd" d="{WORD}"/>'
    write(assets+('lockup-reverse.svg' if reverse else 'lockup.svg'),svg(content,'0 0 680 170',680,170))
write(assets+'app-icon.svg',svg(f'<rect x="62" y="62" width="900" height="900" rx="205" fill="{INK}"/>'+mark(PAPER,LIME),'0 0 1024 1024',1024,1024))

brand='''import SwiftUI

// Generated by tools/generate-brand.py. Original Selected Copy geometry.
struct LindoMark: View {
    var size: CGFloat = 40
    init(size: CGFloat = 40) { self.size = size }
    var body: some View {
        ZStack {
            RoundedRectangle(cornerRadius: size * 0.20, style: .continuous)
                .fill(Color(red: 29/255, green: 46/255, blue: 41/255))
                .padding(size * 0.06)
            LindoGlyph(color: Color(red: 244/255, green: 242/255, blue: 233/255))
        }
        .frame(width: size, height: size)
        .accessibilityHidden(true)
    }
}

struct LindoGlyph: View {
    var color: Color = Color(red: 29/255, green: 46/255, blue: 41/255)
    var foldColor: Color = Color(red: 183/255, green: 227/255, blue: 90/255)
    var body: some View {
        ZStack {
            ExtraCopyShape().fill(foldColor)
            SelectedCopyShape().fill(color)
        }
        .aspectRatio(1, contentMode: .fit)
    }
}
'''
for name,ops in [('ExtraCopyShape',BACK),('SelectedCopyShape',FRONT)]:
    brand+=f'''\nprivate struct {name}: Shape {{
    func path(in rect: CGRect) -> Path {{
        var p = Path()
{swift(ops)}
        return p.applying(CGAffineTransform(scaleX: rect.width / 1024, y: rect.height / 1024)
            .concatenating(CGAffineTransform(translationX: rect.minX, y: rect.minY)))
    }}
}}
'''
write('Sources/Lindo/UI/Brand.swift',brand)
draw='''import AppKit
import Foundation

// Generated by tools/generate-brand.py. Original Selected Copy geometry.
let destination = URL(fileURLWithPath: CommandLine.arguments[1], isDirectory: true)
'''
for name,ops in [('selectedCopyPath',FRONT),('extraCopyPath',BACK)]:
    draw+=f'''func {name}() -> CGPath {{
        let p = CGMutablePath()
{swift(ops)}
        return p
}}
'''
draw+='''for size in [16, 32, 128, 256, 512] {
    for scale in [1, 2] {
        let pixels = size * scale
        let bitmap = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: pixels,
            pixelsHigh: pixels, bitsPerSample: 8, samplesPerPixel: 4,
            hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB,
            bytesPerRow: 0, bitsPerPixel: 0)!
        NSGraphicsContext.saveGraphicsState()
        NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: bitmap)
        let context = NSGraphicsContext.current!.cgContext
        context.scaleBy(x: CGFloat(pixels) / 1024, y: CGFloat(pixels) / 1024)
        context.translateBy(x: 0, y: 1024)
        context.scaleBy(x: 1, y: -1)
        context.setFillColor(NSColor(srgbRed: 29/255, green: 46/255, blue: 41/255, alpha: 1).cgColor)
        context.addPath(CGPath(roundedRect: CGRect(x: 62, y: 62, width: 900, height: 900),
                               cornerWidth: 205, cornerHeight: 205, transform: nil))
        context.fillPath()
        context.setFillColor(NSColor(srgbRed: 183/255, green: 227/255, blue: 90/255, alpha: 1).cgColor)
        context.addPath(extraCopyPath())
        context.fillPath()
        context.setFillColor(NSColor(srgbRed: 244/255, green: 242/255, blue: 233/255, alpha: 1).cgColor)
        context.addPath(selectedCopyPath())
        context.fillPath()
        NSGraphicsContext.restoreGraphicsState()
        let suffix = scale == 2 ? "@2x" : ""
        let file = destination.appendingPathComponent("icon_\\(size)x\\(size)\\(suffix).png")
        try bitmap.representation(using: .png, properties: [:])!.write(to: file)
    }
}
'''
write('tools/draw-icon.swift',draw)
print('Generated vector assets and matching native renderers.')
